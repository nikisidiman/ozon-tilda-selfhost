import { describe, expect, it } from 'vitest'
import { cityFromAddress, hoursFromSchedule } from './pvz-sync.js'

describe('cityFromAddress', () => {
  it.each([
    ['г. Москва, ул. Ленина, д. 1', 'Москва'],
    ['Московская обл., г. Химки, ул. Победы, 3', 'Химки'],
    ['119021, г. Москва, ул. Льва Толстого, 16', 'Москва'],
    ['Санкт-Петербург, Невский пр-т, 88', 'Санкт-Петербург'],
    ['Республика Татарстан, г Казань, ул. Баумана, 44', 'Казань'],
    ['Краснодарский край, ст-ца Динская, ул. Красная, 1', 'Динская'],
    ['Ленинградская обл., пос. Мурино, Охтинская аллея, 4', 'Мурино'],
    ['ул. Ленина, 1', null],
    ['Россия, Краснодарский Край, Краснодар, улица Героев-Разведчиков, 10', 'Краснодар'],
    ['Россия, Краснодарский, Краснодар, улица Тюляева, 16а', 'Краснодар'],
    ['Россия, край Краснодарский, г. Краснодар, ул. им. Героя Сарабеева В.И., д. 5', 'Краснодар'],
    ['Россия, Красноярский Край, Красноярск, улица Мира, 1', 'Красноярск'],
    ['Россия, Краснодар, Центральный внутригородской округ, микрорайон Центральный, Одесская улица, 48литЗ', 'Краснодар'],
    ['Россия, Свердловская обл., Каменск-Уральский, ул. Ленина, 1', 'Каменск-Уральский'],
    ['Россия, 350078, край Краснодарский, г. Краснодар, просп. им Константина Образцова, д. 6', 'Краснодар'],
    ['Россия, Республика Татарстан, г. Казань, ул. Юлиуса Фучика, д. 106, корп. а', 'Казань'],
  ])('%s → %s', (addr, city) => {
    expect(cityFromAddress(addr)).toBe(city)
  })
})

describe('hoursFromSchedule', () => {
  it('часы первого рабочего дня', () => {
    expect(hoursFromSchedule([{ date: '2026-10-22', periods: [{ from_local: '09:00:00', to_local: '21:00:00' }] }])).toBe('09:00–21:00')
    expect(hoursFromSchedule([])).toBeNull()
  })
})
